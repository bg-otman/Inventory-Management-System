export const translate = (lang: Lang) => (key: string) => words[key] || key;
// Translate generated history labels on display, keeping stored history and
// the user's names, notes, and reasons untouched.
export function movementLabel(reason: string, lang: Lang) {
  const t = translate(lang),
    keys: Record<string, string> = {
      'Opening stock': 'openingStock',
      'Sale delivery': 'saleDelivery',
      'Purchase receipt': 'purchaseReceipt',
      'Warehouse transfer': 'warehouseTransfer',
    };
  if (keys[reason]) return t(keys[reason]);
  return reason.startsWith('Reversal: ') ? t('reversalLabel') + ': ' + reason.slice(10) : reason;
}
export function activityLabel(action: string, label: string, lang: Lang) {
  const t = translate(lang);
  if (action === 'stock.adjusted' && label.startsWith('Opening stock: '))
    return t('openingStock') + ': ' + label.slice(15);
  if (action === 'document.saved' && label === 'Draft') return t('draft');
  if (action === 'document.reversed' && label.startsWith('Draft: '))
    return t('draft') + ': ' + label.slice(7);
  if ('sale.delivered'.includes(action) && label === 'Pending invoice') return t('pendingInvoice');
  if (action === 'payment.recorded' && /^\d+(\.\d+)? MAD$/.test(label))
    return (
      new Intl.NumberFormat('fr-MA', { minimumFractionDigits: 2, maximumFractionDigits: 2 }).format(
        Number(label.slice(0, -4)),
      ) +
      ' ' +
      t('MAD')
    );
  return label;
}
